var selftest = require('../tool-testing/selftest.js');
var Sandbox = selftest.Sandbox;

// Bug these tests guard against:
//
// In full-app test mode (`meteor test --full-app`) the app itself must run in
// the browser, so the client side must be bundled. The rspack plugin, however,
// only built the client bundle when a client test entrypoint was configured
// (a testModule.client, or a single-file testModule); the server bundle was
// always built. So `meteor test --full-app` for an app with no client test
// module — eager test-file discovery, or a server-only testModule.server —
// produced a server bundle but left client-rspack.js as the autogenerated
// placeholder. Observable result: the browser received no application code and
// the app never rendered, so client-side full-app tests could not run at all.
//
// Each test below builds such an app in full-app mode and asserts the built
// test-mode client bundle contains real app code, not the placeholder.

const APP_TEMPLATE = 'rspack-full-app';
// Separate fixture whose package.json already declares meteor.testModule.server.
// We use a dedicated app rather than rewriting package.json after createApp:
// mutating package.json between install and first run makes Meteor re-run its
// npm dependency step, which is both slow and (here) unnecessary — and in the
// self-test sandbox that extra step can hang the run.
const SERVER_TEST_TEMPLATE = 'rspack-full-app-server-test';

// Planted in the fixture's client/main.js. A real compiled client bundle
// contains it; the placeholder the plugin writes for a not-built client side
// does not (see the fixture file). So its presence in the built
// _build/test/client-rspack.js is exactly "the client was actually bundled".
const CLIENT_MARKER = 'RSPACK_CLIENT_APP_MARKER';

function checkClientBundleHasAppCode(s) {
  const clientBundle = s.read('_build/test/client-rspack.js');
  if (!clientBundle) {
    selftest.fail('Expected _build/test/client-rspack.js to exist');
  }
  if (!clientBundle.includes(CLIENT_MARKER)) {
    selftest.fail(
      'Expected the test-mode client bundle to contain the app client code ' +
      `(marker ${CLIENT_MARKER}). The bundle is still the autogenerated ` +
      'placeholder, so the browser would load an app without any client code.'
    );
  }
}

selftest.define(
  'rspack: test --full-app without test entrypoints builds the client app bundle',
  ['checkout'],
  async function () {
    // Scenario: full-app test with NO meteor.testModule at all (eager
    // test-file discovery). This hits the plugin's else-branch, where the
    // pre-fix code built only the server bundle unless a testModule was set —
    // so the client bundle was never produced and the app couldn't render.
    const s = new Sandbox();
    await s.init();

    await s.createApp('app', APP_TEMPLATE);
    s.cd('app');

    const run = s.run(
      'test',
      '--full-app',
      '--driver-package', 'test-in-console',
      '--port', '24700'
    );
    // First start downloads/builds npm deps and runs the initial rspack
    // compilation, so give it a generous (but honest) budget.
    run.waitSecs(300);

    // Full-app mode must load the app's main server module...
    await run.match('RSPACK_SERVER_APP_MARKER');
    await run.match('App running at');
    await run.stop();

    // ...and must have produced a real client bundle, not the placeholder.
    checkClientBundleHasAppCode(s);
  }
);

selftest.define(
  'rspack: test --full-app with server-only testModule builds the client app bundle',
  ['checkout'],
  async function () {
    // Scenario: full-app test with ONLY meteor.testModule.server set (no client
    // test entrypoint). This hits the plugin's testClient/testServer branch,
    // where the pre-fix code built the client bundle only when testModule.client
    // was present — so a server-only config still left the client unbundled,
    // even though full-app mode needs the app's client code in the browser.
    const s = new Sandbox();
    await s.init();

    await s.createApp('app', SERVER_TEST_TEMPLATE);
    s.cd('app');

    const run = s.run(
      'test',
      '--full-app',
      '--driver-package', 'test-in-console',
      '--port', '24710'
    );
    run.waitSecs(300);

    // Full-app mode must load the app's main server module and the
    // configured server test module.
    await run.match('RSPACK_SERVER_APP_MARKER');
    await run.match('RSPACK_TEST_SERVER_MARKER');
    await run.match('App running at');
    await run.stop();

    // The client bundle must contain the app's client code even though only
    // testModule.server was configured.
    checkClientBundleHasAppCode(s);
  }
);
